export const DEFAULT_MOVIE = MOCK_TRAI_BUON_NGUOI;

export function getMovieById(id) {
    if (!id) return DEFAULT_MOVIE;
    const strId = String(id).toLowerCase();
    return (
        ALL_MOVIES.find(
            (m) => String(m.id) === strId || m.slug?.toLowerCase() === strId
        ) || DEFAULT_MOVIE
    );
}

export function getNowShowingMovies() {
    return ALL_MOVIES.slice(0, 9).map((m) => ({
        id: m.id,
        src: m.poster,
        name: m.title,
        genre: m.genres ? m.genres.join(', ') : '',
        rate: m.ratingPoint,
        link: `/phim/${m.id}`,
    }));
}

