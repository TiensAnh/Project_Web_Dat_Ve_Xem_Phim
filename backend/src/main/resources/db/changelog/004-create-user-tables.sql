-- Tạo enum phân quyền người dùng
CREATE TYPE user_role AS ENUM ('customer', 'staff', 'brand_admin', 'super_admin');

-- Tạo enum trạng thái tài khoản
CREATE TYPE user_status AS ENUM ('active', 'locked', 'pending');

-- Tạo bảng tài khoản người dùng
CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       email VARCHAR(255) NOT NULL UNIQUE,
                       password_hash VARCHAR(255) NOT NULL,
                       full_name VARCHAR(255) NOT NULL,
                       phone VARCHAR(20),
                       avatar_url TEXT,
                       role user_role NOT NULL DEFAULT 'customer',
                       status user_status NOT NULL DEFAULT 'active',
                       brand_id BIGINT,
                       cinema_id BIGINT,
                       last_login_at TIMESTAMPTZ,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                       updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Tạo chỉ mục tìm kiếm theo quyền và thương hiệu
CREATE INDEX users_role_idx ON users(role);
CREATE INDEX users_brand_id_idx ON users(brand_id);