CREATE TABLE genres(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);
CREATE TYPE movie_status AS ENUM ('coming_soon', 'now_showing', 'ended');
CREATE TYPE age_rating AS ENUM ('P', 'K', 'T13', 'T16', 'T18');
CREATE TABLE movies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(255) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    english_title VARCHAR(255),
    duration_minutes INT NOT NULL,
    age_rating age_rating,
    country VARCHAR(100),
    status movie_status NOT NULL DEFAULT 'coming_soon',
    poster_url TEXT,
    backdrop_url TEXT,
    trailer_url TEXT,
    synopsis TEXT,
    story_plot TEXT,
    highlights TEXT,
    release_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT movies_positive_duration CHECK (duration_minutes > 0)
);
CREATE INDEX movie_status_idx ON movies(status);
CREATE INDEX movie_release_date_idx ON movies(release_date);
CREATE TABLE movie_genres (
    movie_id BIGINT NOT NULL,
    genre_id BIGINT NOT NULL,

    PRIMARY KEY (movie_id, genre_id),
    FOREIGN KEY (movie_id) REFERENCES movies (id),
    FOREIGN KEY (genre_id) REFERENCES genres (id)
);